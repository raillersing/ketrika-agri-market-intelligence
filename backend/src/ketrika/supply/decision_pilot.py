"""Supply decision pilot scenarios and user journeys for key stakeholders (R5.8, ADR-094, SPECS §27).

This module prepares verifiable decision journeys for 3 key market personas in Madagascar:
1. Public Institution / Market Regulator (SPM / MIC / OdR): monitoring urban supply tension, buffer stocks.
2. Commercial Buyer / Agro-industrial Aggregator: procurement planning aligned with arrival peaks.
3. Agricultural Planner / Extension Services (MinAE): analyzing drought shocks and lean season elongation.

Strict constitutional rules:
- Scenarios are strictly deterministic; impacts are calculated mathematically, NEVER generated by LLM.
- Input parameters are sanitized against whitelists; injected prompts/instructions are strictly blocked.
- Mandatory parameters must be present; missing parameters halt computation transparently.
- System strictly NEVER produces automated financial purchase orders (order_generation_prohibited=True).
- Status is transparently 'NOT_EVALUATED' and 'human_reviewed=False' until physical human user testing.
"""

from __future__ import annotations

import re
import uuid
