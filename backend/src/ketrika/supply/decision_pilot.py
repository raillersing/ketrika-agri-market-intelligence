from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field

from ketrika.supply.harvest_window import HarvestWindowProjection, format_dekad_label, shift_dekad
from ketrika.supply.peak_forecast import SupplyWindowPrediction, parse_dekad_label


class DecisionPersona(StrEnum):
    """Target stakeholder persona for the decision pilot."""

    PUBLIC_REGULATOR = "public_regulator"
    COMMERCIAL_BUYER = "commercial_buyer"
    AGRICULTURAL_PLANNER = "agricultural_planner"


class ScenarioParameter(BaseModel):
    """A typed parameter for decision scenario simulations."""

    model_config = ConfigDict(frozen=True)

    name: str
    value: float
    unit: str
    source_justification: str
    default_value: float
    is_user_override: bool = False


class DecisionScenarioDefinition(BaseModel):
    """Specification of an actionable market supply scenario."""

    model_config = ConfigDict(frozen=True)

    scenario_id: str
    title: str
    persona: DecisionPersona
    market_code: str
    product_code: str
    campaign: str
    parameters: dict[str, ScenarioParameter]
    author_id: str = "internal_analyst"
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    version: str = "v1.0"
    human_reviewed: bool = False
    evaluation_status: str = "NOT_EVALUATED"


class DecisionImpactMetric(BaseModel):
    """Quantified mathematical impact of the simulated scenario against baseline."""

    model_config = ConfigDict(frozen=True)

    metric_name: str
    baseline_value: float
    scenario_value: float
    absolute_change: float
    relative_change_pct: float
    unit: str
    interpretation: str


class DecisionPilotReport(BaseModel):
    """Actionable decision support report for human decision makers."""

    model_config = ConfigDict(frozen=True)

    report_id: str
    persona: DecisionPersona
    scenario_id: str
    title: str
    market_code: str
    product_code: str
    campaign: str
    impacts: list[DecisionImpactMetric]
    decision_recommendation: str
    risk_assessment: str
    order_generation_prohibited: bool = True
    missing_parameters: list[str] = Field(default_factory=list)
    human_reviewed: bool = False
    evaluation_status: str = "NOT_EVALUATED"
    provenance_note: str


