    def validate_scenario(
        self,
        scenario: DecisionScenarioDefinition,
    ) -> list[str]:
        """Validate scenario parameters against persona whitelist and check completeness."""
        allowed = ALLOWED_PARAMETERS.get(scenario.persona, set())
        missing = [p for p in allowed if p not in scenario.parameters]

        # Check for unvetted parameters
        for param_key in scenario.parameters:
            if param_key not in allowed:
                raise ValueError(
                    f"Parameter '{param_key}' is not allowed for persona '{scenario.persona.value}'. "
                    f"Allowed parameters: {sorted(allowed)}"
                )

        return missing

    def run_public_regulator_journey(
        self,
        scenario: DecisionScenarioDefinition,
        observed_monthly_arrivals_tonnes: float,
    ) -> DecisionPilotReport:
        """Execute decision journey for Public Institution / Market Regulator."""
        missing = self.validate_scenario(scenario)
        if missing:
            return DecisionPilotReport(
                report_id=str(uuid.uuid4()),
                persona=scenario.persona,
                scenario_id=scenario.scenario_id,
                title=scenario.title,
                market_code=scenario.market_code,
                product_code=scenario.product_code,
                campaign=scenario.campaign,
                impacts=[],
                decision_recommendation="Execution halted: mandatory parameters missing.",
                risk_assessment="INCOMPLETE_DATA",
                missing_parameters=missing,
                provenance_note="Computation aborted due to missing parameters.",
            )

        pop = scenario.parameters["urban_population_served"].value
        cons_g = scenario.parameters["daily_consumption_g_per_capita"].value
        reserve_days = scenario.parameters["reserve_target_days"].value

        # Calculate monthly urban requirement (in tonnes)
        # pop * (cons_g / 1000 kg) * 30 days / 1000 tonnes
        monthly_demand_tonnes = (pop * cons_g * 30.0) / 1_000_000.0
        # Strategic reserve buffer needed
        buffer_stock_tonnes = (monthly_demand_tonnes / 30.0) * reserve_days

        # Balance
        supply_gap_tonnes = observed_monthly_arrivals_tonnes - monthly_demand_tonnes
        coverage_pct = round((observed_monthly_arrivals_tonnes / monthly_demand_tonnes) * 100.0, 1)

        impacts = [
            DecisionImpactMetric(
                metric_name="monthly_urban_demand",
                baseline_value=monthly_demand_tonnes,
                scenario_value=monthly_demand_tonnes,
                absolute_change=0.0,
                relative_change_pct=0.0,
                unit="tonnes/month",
                interpretation=f"Besoins mensuels incompressibles de la population urbaine ({pop:,.0f} hab)",
            ),
            DecisionImpactMetric(
                metric_name="monthly_arrivals_vs_demand",
                baseline_value=monthly_demand_tonnes,
                scenario_value=observed_monthly_arrivals_tonnes,
                absolute_change=round(supply_gap_tonnes, 1),
                relative_change_pct=round(
                    (
                        (observed_monthly_arrivals_tonnes - monthly_demand_tonnes)
                        / monthly_demand_tonnes
                    )
                    * 100.0,
                    1,
                ),
                unit="tonnes/month",
                interpretation=f"Taux de couverture de la demande par les arrivages constatés: {coverage_pct}%",
            ),
            DecisionImpactMetric(
                metric_name="strategic_buffer_reserve_target",
                baseline_value=buffer_stock_tonnes,
                scenario_value=buffer_stock_tonnes,
                absolute_change=0.0,
                relative_change_pct=0.0,
                unit="tonnes",
                interpretation=f"Stock de sécurité cible pour {reserve_days:.0f} jours de réserve",
            ),
        ]

        if coverage_pct >= 100.0:
            rec = "Approvisionnement urbain excédentaire ou équilibré. Recommander le maintien des flux et reconstitution du stock tampon."
            risk = "FAIBLE : Marché bien approvisionné."
        elif coverage_pct >= 80.0:
            rec = "Tension d'approvisionnement modérée. Surveiller les arrivages portuaires et accélérer le dédouanement à Toamasina."
            risk = "MODÉRÉ : Risque de hausse des prix de détail si la soudure se prolonge."
        else:
            rec = "Déficit d'approvisionnement sévère. Alerter la SPM et envisager l'ouverture d'un quota d'importation d'urgence."
            risk = "CRITIQUE : Rupture imminente sur les marchés terminaux."

        return DecisionPilotReport(
            report_id=str(uuid.uuid4()),
            persona=scenario.persona,
            scenario_id=scenario.scenario_id,
            title=scenario.title,
            market_code=scenario.market_code,
            product_code=scenario.product_code,
            campaign=scenario.campaign,
            impacts=impacts,
            decision_recommendation=rec,
            risk_assessment=risk,
            order_generation_prohibited=True,
            missing_parameters=[],
            human_reviewed=False,
            evaluation_status="NOT_EVALUATED",
            provenance_note="Calcul déterministe fondé sur INSTAT/ODR et flux observés. Zéro ordre d'achat automatique.",
        )

    def run_commercial_buyer_journey(
        self,
        scenario: DecisionScenarioDefinition,
        supply_prediction: SupplyWindowPrediction,
    ) -> DecisionPilotReport:
        """Execute decision journey for Commercial Buyer / Agro-industrial Aggregator."""
        missing = self.validate_scenario(scenario)
        if missing:
            return DecisionPilotReport(
                report_id=str(uuid.uuid4()),
                persona=scenario.persona,
                scenario_id=scenario.scenario_id,
                title=scenario.title,
                market_code=scenario.market_code,
                product_code=scenario.product_code,
                campaign=scenario.campaign,
                impacts=[],
                decision_recommendation="Execution halted: mandatory parameters missing.",
                risk_assessment="INCOMPLETE_DATA",
                missing_parameters=missing,
                provenance_note="Computation aborted due to missing parameters.",
            )

        target_vol = scenario.parameters["target_procurement_volume_tonnes"].value
        peak_disc = scenario.parameters["peak_discount_target_pct"].value
        wh_cap = scenario.parameters["warehouse_capacity_tonnes"].value

        # Check storage capacity feasibility
        capacity_utilization_pct = round((target_vol / wh_cap) * 100.0, 1)

        # Baseline non-peak cost benchmark (hypothetical 3,400 MGA/kg)
        baseline_price_kg = 3400.0
        peak_price_kg = baseline_price_kg * (1.0 - (peak_disc / 100.0))
        savings_mga = (baseline_price_kg - peak_price_kg) * target_vol * 1000.0

        impacts = [
            DecisionImpactMetric(
                metric_name="target_procurement_volume",
                baseline_value=target_vol,
                scenario_value=target_vol,
                absolute_change=0.0,
                relative_change_pct=0.0,
                unit="tonnes",
                interpretation=f"Volume cible de collecte représentant {capacity_utilization_pct}% de la capacité d'entrepôt",
            ),
            DecisionImpactMetric(
                metric_name="estimated_procurement_savings",
                baseline_value=baseline_price_kg * target_vol * 1000.0,
                scenario_value=peak_price_kg * target_vol * 1000.0,
                absolute_change=-savings_mga,
                relative_change_pct=-peak_disc,
                unit="MGA",
                interpretation=f"Économie brute estimée par achat ciblé en pic d'arrivage: {savings_mga:,.0f} MGA",
            ),
        ]

        peak_dekad = supply_prediction.predicted_peak_dekad or "INCONNU"
        rec = (
            f"Concentrer 70% des ordres d'achat physique sur la fenêtre de pic prévue '{peak_dekad}' "
            f"({supply_prediction.supply_window_start_dekad} à {supply_prediction.supply_window_end_dekad}) "
            f"pour maximiser la liquidité de transaction et bénéficier de la décote de récolte."
        )

        risk = (
            f"Capacité d'entrepôt adéquate ({wh_cap:,.0f} tonnes). "
            f"Surveiller les retards logistiques en cas de fortes pluies sur la RN2/RN4."
        )

        return DecisionPilotReport(
            report_id=str(uuid.uuid4()),
            persona=scenario.persona,
            scenario_id=scenario.scenario_id,
            title=scenario.title,
            market_code=scenario.market_code,
            product_code=scenario.product_code,
            campaign=scenario.campaign,
            impacts=impacts,
            decision_recommendation=rec,
            risk_assessment=risk,
            order_generation_prohibited=True,
            missing_parameters=[],
            human_reviewed=False,
            evaluation_status="NOT_EVALUATED",
            provenance_note=f"Synchronisation sur la fenêtre d'approvisionnement R5.7 ({supply_prediction.qualification.value}).",
        )

    def run_agricultural_planner_journey(
        self,
        scenario: DecisionScenarioDefinition,
        baseline_harvest_window: HarvestWindowProjection,
    ) -> DecisionPilotReport:
        """Execute decision journey for Agricultural Planner / Extension Services."""
        missing = self.validate_scenario(scenario)
        if missing:
            return DecisionPilotReport(
                report_id=str(uuid.uuid4()),
                persona=scenario.persona,
                scenario_id=scenario.scenario_id,
                title=scenario.title,
                market_code=scenario.market_code,
                product_code=scenario.product_code,
                campaign=scenario.campaign,
                impacts=[],
                decision_recommendation="Execution halted: mandatory parameters missing.",
                risk_assessment="INCOMPLETE_DATA",
                missing_parameters=missing,
                provenance_note="Computation aborted due to missing parameters.",
            )

        shift_dekads = int(scenario.parameters["harvest_shift_dekads"].value)
        yield_red = scenario.parameters["yield_reduction_pct"].value
        base_lean_weeks = scenario.parameters["baseline_lean_season_weeks"].value

        # Calculate shifted window
        s_y, s_m, s_d = parse_dekad_label(baseline_harvest_window.window_start_dekad)
        adj_y, adj_m, adj_d = shift_dekad(s_y, s_m, s_d, shift_dekads)
        shifted_start_dekad = format_dekad_label(adj_y, adj_m, adj_d)

        # Extended lean season in weeks (1 dekad ~= 1.43 weeks)
        added_lean_weeks = shift_dekads * (10.0 / 7.0)
        total_lean_weeks = round(base_lean_weeks + added_lean_weeks, 1)

        impacts = [
            DecisionImpactMetric(
                metric_name="harvest_window_start_delay",
                baseline_value=0.0,
                scenario_value=float(shift_dekads),
                absolute_change=float(shift_dekads),
                relative_change_pct=0.0,
                unit="dekads",
                interpretation=f"Décalage du début de récolte de {baseline_harvest_window.window_start_dekad} à {shifted_start_dekad}",
            ),
            DecisionImpactMetric(
                metric_name="lean_season_duration",
                baseline_value=base_lean_weeks,
                scenario_value=total_lean_weeks,
                absolute_change=round(added_lean_weeks, 1),
                relative_change_pct=round((added_lean_weeks / base_lean_weeks) * 100.0, 1),
                unit="weeks",
                interpretation=f"Prolongation de la soudure vivrière de {added_lean_weeks:.1f} semaines (total: {total_lean_weeks} sem.)",
            ),
            DecisionImpactMetric(
                metric_name="rainfed_production_loss",
                baseline_value=100.0,
                scenario_value=100.0 - yield_red,
                absolute_change=-yield_red,
                relative_change_pct=-yield_red,
                unit="percent",
                interpretation=f"Perte de rendement estimée sous stress hydrique précoce (-{yield_red:.1f}%)",
            ),
        ]

        rec = (
            "Alerter les DRDA et vulgariser le repiquage précoce de variétés à cycle court (ex: Mailaka). "
            "Mobiliser les motopompes et l'irrigation d'appoint sur les périmètres aménagés pour amortir le déficit."
        )

        risk = (
            f"VULNÉRABILITÉ ACCRUE : Les ménages ruraux feront face à une soudure allongée à {total_lean_weeks} semaines. "
            f"Risque d'épuisement des stocks paysans avant l'arrivée de la nouvelle récolte."
        )

        return DecisionPilotReport(
            report_id=str(uuid.uuid4()),
            persona=scenario.persona,
            scenario_id=scenario.scenario_id,
            title=scenario.title,
            market_code=scenario.market_code,
            product_code=scenario.product_code,
            campaign=scenario.campaign,
            impacts=impacts,
            decision_recommendation=rec,
            risk_assessment=risk,
            order_generation_prohibited=True,
            missing_parameters=[],
            human_reviewed=False,
            evaluation_status="NOT_EVALUATED",
            provenance_note="Modélisation agronomique fondée sur les calendriers MinAE/FOFIFA et anomalies CHIRPS.",
        )
