"""Base abstractions, protocols, and data models for Ketrika Connectors (SPECS §9)."""

from __future__ import annotations

import hashlib
import uuid
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from datetime import date, datetime
from typing import Any, ClassVar, Literal, Protocol

from pydantic import BaseModel, Field

from ketrika.core.bronze import BronzeArtifact, BronzeStore
from ketrika.core.http import PoliteHttpClient
from ketrika.core.policy import PolicyEngine, PolicyStop
from ketrika.core.settings import Settings, get_settings


@dataclass(frozen=True)
class DiscoveredItem:
    """An item discovered by connector (URL, document id, partition)."""

    url: str
    partition_key: str | None = None  # e.g. "2025-05" or document ID
    published_at: datetime | None = None
    hints: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class RawArtifact:
    """Raw artifact stored in Bronze layer and tracked in meta.source_record."""

    source_record_id: str  # Created by framework after Bronze write
    object_key: str
    content_sha256: str
    mime_type: str
    url: str
    is_new: bool  # False if sha256 already known (no re-parse needed)
    published_at: datetime | None = None


class RecordBase(BaseModel):
    """Base class for all normalized/parsed records."""

    natural_key_fields: ClassVar[tuple[str, ...]]
    period_start: date
    period_end: date
    extraction_method: Literal["deterministic", "llm_verified", "dual_agree", "human"] = (
        "deterministic"
    )
    evidence: dict[str, Any] = Field(default_factory=dict)
    confidence: float = 1.0

    def compute_natural_key(self, source_id: str) -> str:
        """Compute deterministic SHA-256 natural key based on declared fields and source_id."""
        field_values = [str(getattr(self, k, "")) for k in self.natural_key_fields]
        raw_key = f"{source_id}|" + "|".join(field_values)
        return hashlib.sha256(raw_key.encode("utf-8")).hexdigest()


class ParseResult(BaseModel):
    """Result returned by connector.parse()."""

    records: Sequence[RecordBase] = Field(default_factory=list)
    issues: list[dict[str, Any]] = Field(
        default_factory=list
    )  # {"kind": ..., "detail": ..., "evidence": ...}
    parser_version: str


@dataclass
class RunContext:
    """Execution context provided by the framework to connectors."""

    source_id: str
    settings: Settings = field(default_factory=get_settings)
    http_client: PoliteHttpClient | None = None
    bronze_store: BronzeStore | None = None
    policy_engine: PolicyEngine | None = None
    run_id: uuid.UUID | None = None
    logger: Any = None
    llm_client: Any = None
    offline: bool = False
    metadata: dict[str, Any] = field(default_factory=dict)

    def fetch_and_store(
        self,
        item: DiscoveredItem,
        mime_type: str = "text/plain",
        retrieved_via: str = "direct",
    ) -> RawArtifact:
        """Helper to fetch URL using polite HTTP client and store in Bronze."""
        if self.http_client is None:
            self.http_client = PoliteHttpClient(policy_engine=self.policy_engine)
        if self.bronze_store is None:
            self.bronze_store = BronzeStore()

        resp = self.http_client.get(item.url)
        if resp.is_not_modified:
            raise PolicyStop("http_not_modified_without_known_artifact")
        content_bytes = resp.content
        resp_mime = resp.headers.get("content-type", mime_type).split(";")[0].strip()

        artifact: BronzeArtifact = self.bronze_store.put(
            source_id=self.source_id,
            content=content_bytes,
            mime_type=resp_mime,
            url=item.url,
            retrieved_via=retrieved_via,
            http_status=resp.status_code,
            http_headers=dict(resp.headers),
            fetched_at=datetime.now(),
        )

        # source_record_id is assigned or generated by caller / db runner
        record_id = str(uuid.uuid4())
        return RawArtifact(
            source_record_id=record_id,
            object_key=artifact.object_key,
            content_sha256=artifact.content_sha256,
            mime_type=artifact.mime_type,
            url=artifact.url,
            is_new=artifact.is_new,
            published_at=item.published_at,
        )


